// tools/tier2-worksheet.mjs — writes docs/tier2-buildings.md: the tier-2 candidates per area (buildings not taken
// over by a landmark, with an outer-ring vertex within 12 m of náměstí Republiky (square or street), Pernštýnské náměstí or a třída Míru
// segment), and whether each already has a spec in js/pardubice-building-specs.js.
// usage: node tools/tier2-worksheet.mjs [out.md]
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { PARDUBICE } from '../js/pardubice-geodata.js';
import { BUILDING_SPECS } from '../js/pardubice-building-specs.js';
import { landmarkPlan } from '../js/pardubice-landmark-models.js';

const require = createRequire(import.meta.url);
const { loadBuildings } = require('../tests/helpers/pardubice-buildings.cjs');
const ROOT = fileURLToPath(new URL('../', import.meta.url));
const REACH = 12;

const segDist = (x, z, ax, az, bx, bz) => {
  const dx = bx - ax, dz = bz - az, l2 = dx * dx + dz * dz;
  const t = l2 ? Math.max(0, Math.min(1, ((x - ax) * dx + (z - az) * dz) / l2)) : 0;
  return Math.hypot(x - ax - t * dx, z - az - t * dz);
};
const ringSegments = (flat) => Array.from({ length: flat.length / 2 }, (_, i) =>
  [flat[2 * i], flat[2 * i + 1], flat[(2 * i + 2) % flat.length], flat[(2 * i + 3) % flat.length]]);
const square = (name) => ringSegments(PARDUBICE.squares.find((s) => s.name === name).polygons[0][0]);
const roadSegments = (name) => PARDUBICE.roads.filter((r) => r.name === name)
  .flatMap((r) => Array.from({ length: r.pts.length / 2 - 1 }, (_, i) => r.pts.slice(2 * i, 2 * i + 4)));

export const AREAS = [
  ['republiky', 'náměstí Republiky', [...square('náměstí Republiky'), ...roadSegments('náměstí Republiky')]],
  ['pernstynske', 'Pernštýnské náměstí', square('Pernštýnské náměstí')],
  ['miru', 'třída Míru', [...roadSegments('třída Míru'), ...square('třída Míru')]]
];

export function tier2Candidates(buildings = loadBuildings()) {
  const { replaced } = landmarkPlan(PARDUBICE, buildings);
  const out = Object.fromEntries(AREAS.map(([key]) => [key, []]));
  for (const b of buildings) {
    // Canopies (building=roof: underpass entrances, shelters) get no spec
    if (replaced.has(b.attrs.id) || b.attrs.building === 'roof') continue;
    const near = (segs) => b.polygons[0].outer.some((p) => segs.some((s) => segDist(p.x, p.z, ...s) <= REACH));
    const area = AREAS.find(([, , segs]) => near(segs));
    if (!area) continue;
    const o = b.polygons[0].outer;
    const cx = o.reduce((s, p) => s + p.x, 0) / o.length, cz = o.reduce((s, p) => s + p.z, 0) / o.length;
    out[area[0]].push({ id: b.attrs.id, cp: b.attrs.cp, name: b.attrs.name, levels: b.attrs.levels, building: b.attrs.building,
      x: Math.round(cx), z: Math.round(cz), spec: BUILDING_SPECS[b.attrs.id] });
  }
  for (const list of Object.values(out)) list.sort((a, b) => a.x - b.x || a.z - b.z);
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  const file = process.argv[2] || `${ROOT}docs/tier2-buildings.md`;
  const candidates = tier2Candidates();
  let md = `# Tier-2 buildings worksheet\n\nGenerated by \`tools/tier2-worksheet.mjs\`: the buildings with an outer-ring vertex within ${REACH} m of each area\n` +
    '(landmarks excluded), west to east. A spec lives in `js/pardubice-building-specs.js`; the photo it was written from is\n' +
    'credited in `CREDITS.md`. Coordinates are metres from Zelená brána (x east, z south).\n';
  for (const [key, title] of AREAS) {
    const list = candidates[key];
    md += `\n## ${title} (\`${key}\`): ${list.filter((c) => c.spec).length} of ${list.length} specified\n\n`;
    md += '| OSM id | čp. | name | OSM levels | building | x, z | spec |\n|---|---|---|---|---|---|---|\n';
    for (const c of list) {
      md += `| ${c.id} | ${c.cp || ''} | ${c.name || ''} | ${c.levels || ''} | ${c.building} | ${c.x}, ${c.z} | ${c.spec ? c.spec.label : ''} |\n`;
    }
  }
  fs.writeFileSync(file, md);
  console.log(Object.entries(candidates).map(([k, v]) => `${k} ${v.length}`).join(', '));
}
